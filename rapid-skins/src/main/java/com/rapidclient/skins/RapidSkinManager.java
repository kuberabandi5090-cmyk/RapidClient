package com.rapidclient.skins;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.client.MinecraftClient;
import net.minecraft.client.texture.NativeImage;
import net.minecraft.client.texture.NativeImageBackedTexture;
import net.minecraft.entity.player.PlayerSkinType;
import net.minecraft.entity.player.SkinTextures;
import net.minecraft.util.AssetInfo;
import net.minecraft.util.Identifier;

import java.io.ByteArrayInputStream;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;

public final class RapidSkinManager {
    private static final String SUPABASE_URL = "https://qgcjgmswgjlpuywovcxs.supabase.co";
    // Publishable browser key only. Never place a Supabase secret/service-role key in a client mod.
    private static final String SUPABASE_KEY = "sb_publishable_1w8vaLvqwYI26Qodxy5alQ_Kgcz70mH";
    private static final HttpClient HTTP = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(5))
            .followRedirects(HttpClient.Redirect.NORMAL)
            .build();
    private static final Map<String, SkinTextures> LOADED = new ConcurrentHashMap<>();
    private static final Set<String> REQUESTED = ConcurrentHashMap.newKeySet();

    private RapidSkinManager() {}

    public static void init() {
        System.out.println("[RAPID Skins] Client skin sync initialized for Minecraft 1.21.11");
    }

    public static SkinTextures getSkin(String rawName) {
        if (rawName == null || !rawName.matches("[A-Za-z0-9_]{3,16}")) {
            return null;
        }
        String name = rawName.toLowerCase(Locale.ROOT);
        SkinTextures loaded = LOADED.get(name);
        if (loaded != null) {
            return loaded;
        }
        if (REQUESTED.add(name)) {
            CompletableFuture.runAsync(() -> load(name, rawName))
                    .exceptionally(error -> {
                        REQUESTED.remove(name);
                        System.err.println("[RAPID Skins] Lookup failed for " + rawName + ": " + error.getMessage());
                        return null;
                    });
        }
        return null;
    }

    private static void load(String cacheName, String playerName) {
        try {
            JsonObject payload = new JsonObject();
            payload.addProperty("p_username", playerName);
            HttpRequest lookup = HttpRequest.newBuilder(URI.create(SUPABASE_URL + "/rest/v1/rpc/rapid_skin_lookup"))
                    .timeout(Duration.ofSeconds(8))
                    .header("apikey", SUPABASE_KEY)
                    .header("Authorization", "Bearer " + SUPABASE_KEY)
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(payload.toString()))
                    .build();

            HttpResponse<String> response = HTTP.send(lookup, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 404 || response.statusCode() == 204) {
                REQUESTED.remove(cacheName);
                return;
            }
            if (response.statusCode() != 200) {
                throw new IllegalStateException("profile endpoint returned HTTP " + response.statusCode());
            }

            JsonArray rows = JsonParser.parseString(response.body()).getAsJsonArray();
            if (rows.isEmpty()) {
                REQUESTED.remove(cacheName);
                return;
            }
            JsonObject profile = rows.get(0).getAsJsonObject();
            String path = profile.get("skin_path").getAsString();
            String model = profile.get("model").getAsString();

            // Only accept the exact storage path shape generated by RAPID Accounts.
            if (!path.matches("[0-9a-fA-F-]{36}/skin\\.png")) {
                throw new IllegalStateException("profile returned an invalid skin path");
            }
            String encodedPath = encodePath(path);
            URI skinUri = URI.create(SUPABASE_URL + "/storage/v1/object/public/skins/" + encodedPath);
            HttpRequest skinRequest = HttpRequest.newBuilder(skinUri)
                    .timeout(Duration.ofSeconds(8))
                    .GET()
                    .build();
            HttpResponse<byte[]> skinResponse = HTTP.send(skinRequest, HttpResponse.BodyHandlers.ofByteArray());
            if (skinResponse.statusCode() != 200 || skinResponse.body().length > 524288) {
                throw new IllegalStateException("skin download failed (HTTP " + skinResponse.statusCode() + ")");
            }

            NativeImage image = NativeImage.read(new ByteArrayInputStream(skinResponse.body()));
            if (image == null || image.getWidth() != 64 || (image.getHeight() != 64 && image.getHeight() != 32)) {
                if (image != null) image.close();
                throw new IllegalStateException("skin PNG must be 64x64 or 64x32");
            }

            PlayerSkinType skinType = "slim".equalsIgnoreCase(model) ? PlayerSkinType.SLIM : PlayerSkinType.WIDE;
            MinecraftClient.getInstance().execute(() -> {
                try {
                    NativeImageBackedTexture texture = new NativeImageBackedTexture(
                            () -> "RAPID skin for " + playerName, image);
                    Identifier textureId = MinecraftClient.getInstance().getTextureManager()
                            .registerDynamicTexture("rapid_skin", texture);
                    SkinTextures textures = new SkinTextures(
                            new AssetInfo.TextureAssetInfo(textureId),
                            null,
                            null,
                            skinType,
                            false
                    );
                    LOADED.put(cacheName, textures);
                } catch (Exception error) {
                    image.close();
                    System.err.println("[RAPID Skins] Could not register skin for " + playerName + ": " + error.getMessage());
                } finally {
                    REQUESTED.remove(cacheName);
                }
            });
        } catch (Exception error) {
            REQUESTED.remove(cacheName);
            System.err.println("[RAPID Skins] Could not load skin for " + playerName + ": " + error.getMessage());
        }
    }

    private static String encodePath(String path) {
        String[] parts = path.split("/");
        return URLEncoder.encode(parts[0], StandardCharsets.UTF_8) + "/"
                + URLEncoder.encode(parts[1], StandardCharsets.UTF_8);
    }
}
